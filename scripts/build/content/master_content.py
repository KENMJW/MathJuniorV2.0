def get_master_content(example_id: str, bound_target_id: str):
    """
    根据 example_id 与绑定的 target_id 生成定制化的 dim1_origin, dim2_essence, dim4_traps
    """
    # 1. 主线母题
    if example_id in LINE_MASTERS_CONTENT:
        return LINE_MASTERS_CONTENT[example_id]

    # 2. 考点母题 (ME-KP001 ~ ME-KP107)
    kp_data = ALL_KPS.get(bound_target_id)
    if not kp_data:
        raise ValueError(f"Target KP {bound_target_id} not found in knowledge points database!")

    # 针对具体考点提炼母题四维解析
    dim1 = f"本题针对考点【{bound_target_id}】的核心考查要求进行命题设计。命题意图在于检验学生对该概念在具体数学情境中的原点由来与数学本质的理解：{kp_data['origin_story_zh']}"
    dim2 = f"本题解题题眼与核心等量关系：{kp_data['intuitive_essence_zh']}"
    dim4 = f"解题易错陷阱与中考变式迁移：{kp_data['intrinsic_variation_zh']}"

    return {
        "dim1_origin": dim1,
        "dim2_essence": dim2,
        "dim4_traps": dim4
    }
