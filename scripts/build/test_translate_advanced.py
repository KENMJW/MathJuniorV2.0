def translate_full_stem(stem_zh):
    if not stem_zh:
        return ""
        
    math_tokens = []
    def save_math(m):
        math_tokens.append(m.group(0))
        return f"__MATH_{len(math_tokens)-1}__"
    
    img_tokens = []
    def save_img(m):
        img_tokens.append(m.group(0))
        return f"__IMG_{len(img_tokens)-1}__"
        
    text = re.sub(r'\[\[IMG:\d+\]\]', save_img, stem_zh)
    text = re.sub(r'\$\$[^\$]+\$\$|\$[^\$]+\$', save_math, text)
    
    # Apply full template
    for pat, repl in PHRASE_MAP:
        if re.search(pat, text):
            text = re.sub(pat, repl, text)
            break
            
    # Apply term replacements
    for zh, en in TERM_REPLACEMENTS:
        text = text.replace(zh, en)
        
    # Clean redundant punctuation and spaces
    text = text.replace("，", ", ").replace("。", ". ").replace("；", "; ").replace("：", ": ")
    text = re.sub(r' +', ' ', text).strip()
    
    # Restore image tokens
    for i, tok in enumerate(img_tokens):
        text = text.replace(f"__IMG_{i}__", tok)
        
    # Restore math tokens
    for i, tok in enumerate(math_tokens):
        text = text.replace(f"__MATH_{i}__", tok)
        
    return text

conn = sqlite3.connect('data/questions.db')
cur = conn.cursor()
rows = cur.execute('SELECT question_id, stem_zh FROM questions WHERE content_status = \"done\" LIMIT 15;').fetchall()
for qid, zh in rows:
    print(qid, '->', translate_full_stem(zh)[:80])
